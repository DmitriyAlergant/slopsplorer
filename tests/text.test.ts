import { describe, expect, it } from "vitest";
import { decodeText, readFailure } from "../src/scanner/text.ts";
import { hasGeneratedContent, isGenerated } from "../src/scanner/classify.ts";

describe("content detection", () => {
  it("accepts empty, Unicode and BOM-marked text", () => {
    for (const text of ["", "hello\n", "Привет 世界\n", "\ufeffhello\n"]) {
      expect(decodeText(Buffer.from(text))).toEqual({ text: text.replace(/^\ufeff/, ""), reason: null });
    }
  });
  it("decodes both UTF-16 byte orders before checking for binary controls", () => {
    const littleEndian = Buffer.concat([Buffer.from([0xff, 0xfe]), Buffer.from("Hello 世界\n", "utf16le")]);
    const bigEndian = Buffer.from(littleEndian).swap16();
    for (const buffer of [littleEndian, bigEndian]) {
      expect(decodeText(buffer)).toEqual({ text: "Hello 世界\n", reason: null });
    }
  });
  it("separates binary data from unsupported encoding without replacement characters", () => {
    expect(decodeText(Buffer.from([65, 0, 66]))).toEqual({ text: null, reason: "binary" });
    expect(decodeText(Buffer.from([1, 2, 3]))).toEqual({ text: null, reason: "binary" });
    expect(decodeText(Buffer.from([0xc3, 0x28]))).toEqual({ text: null, reason: "unsupported-encoding" });
    expect(decodeText(Buffer.from([0xff, 0xfe, 65]))).toEqual({ text: null, reason: "unsupported-encoding" });
  });
  it("reports expected read failures and propagates unexpected errors", () => {
    expect(readFailure(Object.assign(new Error("missing"), { code: "ENOENT" }))).toEqual({ text: null, reason: "unreadable" });
    const unexpected = new Error("bug");
    expect(() => readFailure(unexpected)).toThrow(unexpected);
    expect(() => readFailure(Object.assign(new Error("IO failed"), { code: "EIO" }))).toThrow("IO failed");
  });
});

it("does not mistake generator markers quoted in patches for the patch's own origin", () => {
  for (const name of ["fix.patch", "fix.diff"]) {
    expect(isGenerated(name)).toBe(false);
    expect(hasGeneratedContent(name, "// Generated by a compiler\n-old\n+new\n")).toBe(false);
    expect(isGenerated(`generated/${name}`)).toBe(true);
  }
});
